"""Standardized incident report generation."""

from __future__ import annotations

import os
import uuid
from datetime import datetime, timezone

from .models import AlertPayload, AnalysisResult, IncidentReport, RemediationResult


def generate_report(
    alert: AlertPayload,
    analysis: AnalysisResult,
    remediation: RemediationResult,
    timeline: list[str] | None = None,
) -> IncidentReport:
    incident_id = f"INC-{uuid.uuid4().hex[:8].upper()}"
    tl = list(timeline or [])
    tl.append(f"{alert.fired_at.isoformat()} Alert fired: {alert.summary}")
    tl.append(f"{analysis.analyzed_at.isoformat()} Root cause identified: {analysis.root_cause}")
    tl.append(f"{remediation.executed_at.isoformat()} Remediation: {remediation.message}")

    markdown = f"""# Incident Report: {incident_id}

## Summary
- **Service:** {alert.service}
- **Severity:** {alert.severity.value}
- **Alert ID:** {alert.alert_id}
- **Source:** {alert.source.value}
- **Fired at:** {alert.fired_at.isoformat()}

## Root Cause
{analysis.root_cause}

**Confidence:** {analysis.confidence:.2f}

## Remediation Action
- **Action:** {remediation.action.value}
- **Target:** {remediation.target or "n/a"}
- **Result:** {"SUCCESS" if remediation.success else "FAILED"}
- **Dry run:** {remediation.dry_run}
- **Message:** {remediation.message}

## Timeline
{chr(10).join("- " + t for t in tl)}

## AI Draft (SOP Update)
{analysis.incident_report_draft}

---
*Generated by SovereignGuard Ops Bot*
"""
    return IncidentReport(
        incident_id=incident_id,
        alert_id=alert.alert_id,
        service=alert.service,
        severity=alert.severity,
        root_cause=analysis.root_cause,
        remediation=remediation.message,
        timeline=tl,
        report_markdown=markdown,
    )


def persist_report(report: IncidentReport, directory: str) -> str:
    os.makedirs(directory, exist_ok=True)
    path = os.path.join(directory, f"{report.incident_id}.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(report.report_markdown)
    return path


def create_incident_report(*args, **kwargs):
    return generate_report(*args, **kwargs)

def save_report(*args, **kwargs):
    return persist_report(*args, **kwargs)
